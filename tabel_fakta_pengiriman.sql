create table testing2_fakta_pengiriman(
no_resi varchar primary key not null,
waktu_transaksi  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
id_pegawai_pembuat_kantor_asal varchar(10) not null,
id_user varchar(100),
nama_pengirim text not null,
no_hp_pengirim varchar(15) not null,
alamat_detail_pengirim text not null,
id_layanan varchar(20) not null,
id_tarif int not null,
berat_gram int not null,
berat_dikenakan int not null,
total_tarif NUMERIC(14,2) not null,
id_tipe_pembayaran varchar(10) not null,
id_kabkota_pengirim int not null,
id_kantor_pengirim  varchar(10) not null,
id_pegawai_penerima_kantor_tujuan varchar(10),
id_kabkota_penerima int  not null,
id_kantor_penerima varchar(10) not null,
id_mitra varchar(10) not null,
id_status_terakhir varchar(10) not null,
nama_penerima text not null,
no_hp_penerima varchar(15) not null,
alamat_detail_penerima text not null,
waktu_update_terakhir TIMESTAMPTZ NOT NULL DEFAULT NOW(),
waktu_sampai TIMESTAMPTZ,
foreign key(id_pegawai_pembuat_kantor_asal) references dim_pegawai(id_pegawai),
foreign key(id_user) references dim_user(id_user),
foreign key(id_layanan) references dim_layanan(id_layanan),
foreign key(id_tarif) references tarif_pengiriman(id_tarif),
foreign key(id_tipe_pembayaran) references dim_tipe_pembayaran(id_tipe_pembayaran),
foreign key(id_kabkota_pengirim) references dim_kabkota(id_kabkota),
foreign key(id_kantor_pengirim) references dim_kantor(id_kantor),
foreign key(id_pegawai_penerima_kantor_tujuan) references dim_pegawai(id_pegawai),
foreign key(id_kabkota_penerima) references dim_kabkota(id_kabkota),
foreign key(id_kantor_penerima) references dim_kantor(id_kantor),
foreign key(id_mitra) references dim_mitra(id_mitra),
foreign key(id_status_terakhir) references dim_status_pengiriman(id_status),

CONSTRAINT chk_berat_gram CHECK (berat_gram > 0),

CONSTRAINT chk_berat_dikenakan CHECK (berat_dikenakan > 0),

CONSTRAINT chk_total_tarif CHECK (total_tarif >= 0)
)
